"""从应用注册和真实 Context 签名生成开发者使用的完整类型声明。"""

from __future__ import annotations

import ast
import inspect
import types
from collections.abc import Mapping
from functools import reduce
from operator import or_
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

from .actions import TrustedAction, application_actions
from .run_context import RunContext


def _signature(function) -> inspect.Signature:
    """跟随包装器签名，并在原函数命名空间解析延迟注解。"""
    original = inspect.unwrap(function)
    return inspect.signature(function, globals=original.__globals__, eval_str=True)


def _annotation(annotation):
    """将运行时支持的 JSON 注解规范为可独立导入的声明，拒绝未支持的外部类型。"""
    if annotation in {str, int, float, bool, type(None), None, Any}:
        return annotation
    origin, arguments = get_origin(annotation), get_args(annotation)
    if origin in {list, dict} and arguments:
        return origin[tuple(_annotation(item) for item in arguments)]
    if origin in {types.UnionType, Union}:
        return reduce(or_, (_annotation(item) for item in arguments))
    if origin is Literal:
        return annotation
    raise ValueError(f"Unsupported Action annotation: {annotation!r}")


def _action_signature(name: str, action: TrustedAction) -> inspect.Signature:
    """移除执行器注入参数，将公开输入约束为 ctx.action 支持的关键字参数。"""
    signature = _signature(action.execute)
    parameters = list(signature.parameters.values())
    if not parameters or parameters[0].kind not in {
        inspect.Parameter.POSITIONAL_ONLY, inspect.Parameter.POSITIONAL_OR_KEYWORD,
    } or parameters[0].default is not inspect.Parameter.empty:
        raise ValueError(f"{name}: expected a required first Context parameter")
    public = []
    for parameter in parameters[1:]:
        if parameter.kind not in {inspect.Parameter.POSITIONAL_OR_KEYWORD, inspect.Parameter.KEYWORD_ONLY}:
            raise ValueError(f"{name}: unsupported Action parameter {parameter.name}")
        if parameter.annotation is inspect.Parameter.empty:
            raise ValueError(f"{name}: missing annotation for {parameter.name}")
        if parameter.name in {"self", "logical_name"}:
            raise ValueError(f"{name}: Action parameter conflicts with ctx.action: {parameter.name}")
        public.append(parameter.replace(kind=inspect.Parameter.KEYWORD_ONLY, annotation=_annotation(parameter.annotation)))
        if parameter.default is not inspect.Parameter.empty:
            try:
                ast.literal_eval(repr(parameter.default))
            except (ValueError, SyntaxError) as error:
                raise ValueError(f"{name}: unsupported default for {parameter.name}") from error
    if signature.return_annotation is inspect.Signature.empty:
        raise ValueError(f"{name}: missing return annotation")
    return signature.replace(return_annotation=_annotation(signature.return_annotation), parameters=[
        inspect.Parameter("self", inspect.Parameter.POSITIONAL_OR_KEYWORD),
        inspect.Parameter("logical_name", inspect.Parameter.POSITIONAL_OR_KEYWORD, annotation=Literal[name]),
        *public,
    ])


def render_stubs(actions: Mapping[str, TrustedAction] | None = None) -> str:
    """生成全部公开成员；Action 名称及参数只来自本次应用注册。"""
    actions = application_actions() if actions is None else actions
    if not actions:
        raise ValueError("Cannot generate Action types from an empty registry")
    lines = [
        '# Generated by uv run lalc generate-stubs; do not edit.',
        'import typing',
        'from typing import Any, Literal',
        'from .runtime import WorkflowExecutor',
        '',
        '',
        'class RunContext:',
    ]
    for name, member in vars(RunContext).items():
        if name.startswith('_') and name != '__init__':
            continue
        if name == 'action':
            for logical_name, action in sorted(actions.items()):
                try:
                    signature = _action_signature(logical_name, action)
                except (ValueError, TypeError, NameError) as error:
                    raise ValueError(f"Cannot generate {logical_name}: {error}") from error
                if len(actions) > 1:
                    lines.append('    @typing.overload')
                lines.append(f'    def action{signature}: ...')
        else:
            if isinstance(member, property):
                lines.append('    @property')
                member = member.fget
            # 构造器引用仅在 TYPE_CHECKING 时导入的 Executor，保留其前向引用。
            signature = inspect.signature(member) if name == '__init__' else _signature(member)
            lines.append(f'    def {name}{signature}: ...')
        lines.append('')
    return '\n'.join(lines)


def generate_stubs() -> Path:
    """先完整生成，再覆盖包内声明；签名或写入错误由 CLI 显示并返回失败。"""
    content = render_stubs()
    target = Path(__file__).with_name('run_context.pyi')
    target.write_text(content, encoding='utf-8')
    return target
